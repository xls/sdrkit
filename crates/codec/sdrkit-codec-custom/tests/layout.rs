fn profile(p: &str) -> Profile {
    match p {
        "3.2" => Profile::P3_2,
        "4.8" => Profile::P4_8,
        "6.0" => Profile::P6_0,
        "8.0" => Profile::P8_0,
        "12" => Profile::Hq12,
        "16" => Profile::Hq16,
        _ => unreachable!(),
    }
}

#[test]
fn every_appendix_a_row_matches() {
    assert_eq!(ROWS.len(), 44);
    for r in ROWS {
        let cfg = Config {
            rate: if r.rate == 16000 {
                SampleRate::Hz16000
            } else {
                SampleRate::Hz8000
            },
            frame: if r.ms == 20 {
                FrameLength::Ms20
            } else {
                FrameLength::Ms40
            },
            profile: profile(r.profile),
            type_in_band: r.ib == 1,
        };
        let name = format!("{} {} {} ib{}", r.rate, r.ms, r.profile, r.ib);
        let l = Layout::new(cfg).unwrap_or_else(|e| panic!("{name}: {e}"));
        assert_eq!(l.speech_bits, r.b, "{name} B");
        assert_eq!((l.l, l.s), (r.l, r.s), "{name} L S");
        assert_eq!(l.lsf_bits, r.lsf, "{name} lsf");
        assert_eq!(
            (
                l.interp_bits,
                l.res,
                l.lag0_bits,
                l.lagd_bits,
                l.gp_bits,
                l.gc_bits
            ),
            (r.interp, r.res, r.lag0, r.lagd, r.gp, r.gc),
            "{name} side"
        );
        let hb = l
            .hb_on
            .then_some((l.hb_level_bits, l.hb_mode, l.hb_time_bits));
        assert_eq!(hb, r.hb, "{name} hb");
        assert_eq!(&l.pulses[..l.s], r.k, "{name} K");
        assert_eq!(&l.pulse_bits[..l.s], r.pb, "{name} pulse bits");
        assert_eq!(l.pad_bits, r.pad, "{name} pad");
        assert_eq!(
            (l.class_a, l.class_b, l.class_c),
            (r.a, r.bb, r.c),
            "{name} classes"
        );
        assert_eq!(
            (l.payload_bits, l.payload_bytes),
            (r.payload_bits, r.payload_bytes),
            "{name} payload"
        );
        assert_eq!(l.sid_bytes, r.sid, "{name} sid");
        assert_eq!(l.delay, r.delay, "{name} delay");
    }
}

#[test]
fn bad_configurations_are_refused() {
    let base = Config {
        rate: SampleRate::Hz16000,
        frame: FrameLength::Ms20,
        profile: Profile::P3_2,
        type_in_band: false,
    };
    assert!(Layout::new(base).is_err());
    assert!(Layout::new(Config {
        profile: Profile::Custom(20),
        ..base
    })
    .is_err());
    assert!(Layout::new(Config {
        profile: Profile::Custom(401),
        ..base
    })
    .is_err());
    assert!(Layout::new(Config {
        profile: Profile::Custom(200),
        ..base
    })
    .is_ok());
}
