// The base letter and accent of a Latin-1 letter: 0 none (a plain base letter), 1 grave, 2 acute, 3 circumflex, 4 tilde,
// 5 diaeresis, 6 ring.
fn latin1(c: char) -> Option<(char, u8)> {
    let (b, a) = match c {
        'À' | 'à' => ('A', 1),
        'Á' | 'á' => ('A', 2),
        'Â' | 'â' => ('A', 3),
        'Ã' | 'ã' => ('A', 4),
        'Ä' | 'ä' => ('A', 5),
        'Å' | 'å' => ('A', 6),
        'Ç' | 'ç' => ('C', 0),
        'È' | 'è' => ('E', 1),
        'É' | 'é' => ('E', 2),
        'Ê' | 'ê' => ('E', 3),
        'Ë' | 'ë' => ('E', 5),
        'Ì' | 'ì' => ('I', 1),
        'Í' | 'í' => ('I', 2),
        'Î' | 'î' => ('I', 3),
        'Ï' | 'ï' => ('I', 5),
        'Ñ' | 'ñ' => ('N', 4),
        'Ò' | 'ò' => ('O', 1),
        'Ó' | 'ó' => ('O', 2),
        'Ô' | 'ô' => ('O', 3),
        'Õ' | 'õ' => ('O', 4),
        'Ö' | 'ö' => ('O', 5),
        'Ø' | 'ø' => ('O', 0),
        'Ù' | 'ù' => ('U', 1),
        'Ú' | 'ú' => ('U', 2),
        'Û' | 'û' => ('U', 3),
        'Ü' | 'ü' => ('U', 5),
        'Ý' | 'ý' | 'ÿ' => ('Y', 2),
        _ => return None,
    };
    Some((b, a))
}

fn find(table: &[(char, Glyph)], c: char) -> Option<Glyph> {
    table.iter().find(|e| e.0 == c).map(|e| e.1)
}

/// The glyph of `c`, or `None` when the font does not cover it.
pub fn glyph(c: char) -> Option<Glyph> {
    let up = c.to_uppercase().next().unwrap_or(c);
    if let Some(g) = find(ASCII, up) {
        return Some(g);
    }
    if let Some(&(_, l)) = LOOKALIKE.iter().find(|e| e.0 == up) {
        return find(ASCII, l);
    }
    if let Some(g) = find(EXTRA, up) {
        return Some(g);
    }
    let (base, accent) = latin1(c)?;
    let mut g = find(ASCII, base)?;
    // The base letter goes into the lower four rows (its second row from the top is dropped) and the accent into the top row.
    let rows = g.rows;
    g.rows = [0, rows[0], rows[2], rows[3], rows[4], 0, 0, 0];
    let w = g.width as usize;
    let mid = w / 2;
    let mut mark = |x: usize| g.rows[0] |= 1 << (w - 1 - x.min(w - 1));
    match accent {
        1 => mark(mid.saturating_sub(1)),
        2 => mark(mid + 1),
        3..=6 => {
            mark(mid.saturating_sub(1));
            mark(mid + 1);
            if accent == 3 || accent == 6 {
                mark(mid);
            }
        }
        _ => {}
    }
    Some(g)
}
