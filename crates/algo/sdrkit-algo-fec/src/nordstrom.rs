//! The (16, 256, 6) Nordstrom-Robinson code in a systematic form: eight message bits and eight parity bits, minimum distance 6,
//! with a max-log soft decoder over its 256 words.
//!
//! Standard: GB 20600-2006 (the NR code of 4QAM-NR). The parity table comes from the specification of the DTMB frame decoder; no
//! printed copy of the standard was compared with it.

/// Bit `i` of a 16-bit word, the word sent `x0 .. x7` then `y0 .. y7` with `x0` the most significant bit.
#[inline]
fn bit(w: u16, i: usize) -> u16 {
    (w >> (15 - i)) & 1
}

