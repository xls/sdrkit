/// The code word of message byte `x`: `x` in the high byte, its parity in the low byte.
pub fn encode(x: u8) -> u16 {
    ((x as u16) << 8) | PARITY[x as usize] as u16
}

/// Writes the 16 bits of the code word of `x` to `out` in sent order, one bit per byte.
pub fn encode_bits(x: u8, out: &mut [u8; 16]) {
    let w = encode(x);
    for (i, o) in out.iter_mut().enumerate() {
        *o = bit(w, i) as u8;
    }
}

/// The max-log soft decoder: for the 16 received LLRs of one word (sent order, positive favours 0) writes the 8 message LLRs
/// (positive favours 0). The cost of a word is the sum of the LLRs where it has a 1; the LLR of `x_i` is the least cost over
/// the words with `x_i = 1` less the least cost over the words with `x_i = 0`. Any two flipped bits are corrected.
pub fn decode_soft(llr: &[f32; 16], out: &mut [f32; 8]) {
    // Costs of all message bytes and all parity bytes, then of the 256 words.
    let mut cx = [0f32; 256];
    let mut cy = [0f32; 256];
    for v in 1..256usize {
        let low = v.trailing_zeros() as usize;
        let rest = v & (v - 1);
        cx[v] = cx[rest] + llr[7 - low];
        cy[v] = cy[rest] + llr[15 - low];
    }
    let mut cost = [0f32; 256];
    for (x, c) in cost.iter_mut().enumerate() {
        *c = cx[x] + cy[PARITY[x] as usize];
    }
    for (i, o) in out.iter_mut().enumerate() {
        let m = 0x80usize >> i;
        let (mut one, mut zero) = (f32::INFINITY, f32::INFINITY);
        for (x, &c) in cost.iter().enumerate() {
            if x & m != 0 {
                one = one.min(c);
            } else {
                zero = zero.min(c);
            }
        }
        *o = one - zero;
    }
}

/// The message byte nearest to 16 hard bits (sent order) in Hamming distance, and that distance.
pub fn decode_hard(bits: &[u8; 16]) -> (u8, u32) {
    let r = bits.iter().fold(0u16, |a, &b| (a << 1) | (b & 1) as u16);
    (0..=255u8)
        .map(|x| (x, (encode(x) ^ r).count_ones()))
        .min_by_key(|&(_, d)| d)
        .unwrap_or((0, 16))
}
