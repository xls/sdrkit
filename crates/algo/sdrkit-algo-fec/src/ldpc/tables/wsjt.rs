/// JS8 (174,87) column order. Build the 174-bit word `w` = the 87 parity bits (row order of [`JS8_GENERATOR_HEX`]) followed
/// by the 87 information bits; then the transmitted codeword is `c[JS8_COLUMN_ORDER[i]] = w[i]` for i in 0..174.
