//! The TD-SCDMA code tables and code rules (1.28 Mcps TDD): the 128 basic midambles, the 32 SYNC-DL codes and the 128 scrambling
//! codes, each in its complex form `j^i x_i` (`i` from 1), the midamble shifts, the channelisation codes and the phase quadruples
//! of the SYNC-DL.
//!
//! Standard: 3GPP TS 25.221 Annex AA.1 and clause 5A.2.3 (midambles); TS 25.223 Annex A, Annex AA.1, clauses 6.3, 6.4 and 8.1
//! (scrambling, SYNC-DL, channelisation, quadruples). The tables are written as in TS 25.221 table 8I: element `+1` is bit 1,
//! `-1` is bit 0, the first element the most significant bit.

use sdrkit_core::Complex32;

/// Chips of a sub-frame (5 ms).
pub const SUBFRAME_CHIPS: usize = 6400;
/// The first chip of the SYNC-DL in a sub-frame (after TS0 and the 32 guard chips of the DwPTS).
pub const SYNC_DL_START: usize = 896;
/// The first chip of the DwPTS.
pub const DWPTS_START: usize = 864;
/// Chips of the SYNC-DL.
pub const SYNC_DL_CHIPS: usize = 64;
/// Chips of a basic midamble.
pub const MIDAMBLE_CHIPS: usize = 128;
/// Chips of a midamble with its extension.
pub const MIDAMBLE_LEN: usize = 144;
/// The first chip of the midamble of a traffic burst.
pub const MIDAMBLE_START: usize = 352;
/// Chips of a time slot.
pub const SLOT_CHIPS: usize = 864;
/// The first chip of time slot `n` (1 to 6) of a sub-frame.
pub const fn slot_start(n: usize) -> usize {
    1216 + SLOT_CHIPS * (n - 1)
}
/// Midambles in time slot 0, and the shift between them.
pub const K_TS0: usize = 8;
/// The shift between the midambles of time slot 0, `floor(128 / K)`.
pub const W_TS0: usize = MIDAMBLE_CHIPS / K_TS0;

/// The quadruple S1: a P-CCPCH is in the next four sub-frames (degrees).
pub const S1: [f64; 4] = [135.0, 45.0, 225.0, 135.0];
/// The quadruple S2: no P-CCPCH in the next four sub-frames (degrees).
pub const S2: [f64; 4] = [315.0, 225.0, 315.0, 45.0];

/// `j^i` for `i` from 1.
fn j_pow(i: usize) -> Complex32 {
    match i % 4 {
        0 => Complex32::new(1.0, 0.0),
        1 => Complex32::new(0.0, 1.0),
        2 => Complex32::new(-1.0, 0.0),
        _ => Complex32::new(0.0, -1.0),
    }
}

/// The `len` elements of a table word, first element first: bit 1 is `+1`, bit 0 is `-1`.
fn elements(word: u128, len: usize) -> impl Iterator<Item = f32> {
    (0..len).map(move |k| if (word >> (len - 1 - k)) & 1 == 1 { 1.0 } else { -1.0 })
}

/// The complex form `j^i x_i` (`i = 1 .. len`) of a table word.
fn complex(word: u128, len: usize) -> Vec<Complex32> {
    elements(word, len)
        .enumerate()
        .map(|(k, v)| j_pow(k + 1) * v)
        .collect()
}

/// The complex SYNC-DL code `code` (0 to 31), 64 chips (TS 25.223 8.1 equation (1)).
pub fn sync_dl(code: usize) -> Vec<Complex32> {
    complex(u128::from(SYNC_DL[code % 32]), SYNC_DL_CHIPS)
}

/// The complex basic midamble of cell parameter `p` (0 to 127), 128 chips (TS 25.221 5A.2.3 equation (3)).
pub fn basic_midamble(p: usize) -> Vec<Complex32> {
    complex(MIDAMBLE[p % 128], MIDAMBLE_CHIPS)
}

/// Midamble `k` (1 to `kk`) of 144 chips from the complex basic code `basic`: `m(k)_i = m_(i + (kk - k) w)` over the basic code
/// extended periodically, `w = floor(128 / kk)`. The form of TS 25.221 5A.2.3 equations (4) to (8) as this stack applies it;
/// it is not confirmed against the clause text.
pub fn midamble(basic: &[Complex32], k: usize, kk: usize) -> Vec<Complex32> {
    let w = MIDAMBLE_CHIPS / kk;
    let off = (kk - k) * w;
    (0..MIDAMBLE_LEN)
        .map(|i| basic[(i + off) % MIDAMBLE_CHIPS])
        .collect()
}

/// The complex scrambling code of cell parameter `p`, 16 chips repeated (TS 25.223 6.4 equation (5)).
pub fn scrambling(p: usize) -> Vec<Complex32> {
    complex(u128::from(SCRAMBLING[p % 128]), 16)
}

/// The channelisation code `c(Q = 16, k)`, `k` from 1 as in TS 25.223 6.3: the OVSF code of index `k - 1`. The complex
/// multipliers `w(Q, k)` of that clause are not applied (their values are not confirmed).
pub fn channelisation(k: usize) -> Vec<f32> {
    sdrkit_algo_modem::spreading::ovsf(16, k - 1)
        .into_iter()
        .map(f32::from)
        .collect()
}

/// The code group (= SYNC-DL code) of cell parameter `p`.
pub const fn group(p: usize) -> usize {
    p / 4
}

