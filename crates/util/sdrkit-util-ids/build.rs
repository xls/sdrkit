//! Turns the tab-separated tables in `data/` into static Rust arrays (sorted keys for binary search and one string pool per
//! table, so a lookup never allocates). A malformed row, a duplicate key or a value out of range stops the build with the file
//! and line, so a bad data update cannot ship.

use std::collections::BTreeMap;
use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

/// One data row: its line number and its cells.
struct Row {
    line: usize,
    cells: Vec<String>,
}

fn read_rows(path: &Path, columns: usize) -> Vec<Row> {
    println!("cargo:rerun-if-changed={}", path.display());
    let text = fs::read_to_string(path).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
    let mut rows = Vec::new();
    for (i, line) in text.lines().enumerate() {
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let cells: Vec<String> = line.split('\t').map(str::to_string).collect();
        if cells.len() != columns {
            panic!(
                "{}:{}: {} columns, expected {columns}",
                path.display(),
                i + 1,
                cells.len()
            );
        }
        rows.push(Row { line: i + 1, cells });
    }
    rows
}

fn bad(path: &Path, row: &Row, what: &str) -> ! {
    panic!("{}:{}: {what}", path.display(), row.line)
}

/// A deduplicated string pool: the generated `Pool` keeps one text and the end offset of each string.
#[derive(Default)]
struct Pool {
    text: String,
    ends: Vec<u32>,
    index: BTreeMap<String, u16>,
}

impl Pool {
    fn add(&mut self, s: &str) -> u16 {
        if let Some(&i) = self.index.get(s) {
            return i;
        }
        let i =
            u16::try_from(self.ends.len()).expect("more than 65535 distinct strings in one table");
        self.text.push_str(s);
        self.ends
            .push(u32::try_from(self.text.len()).expect("string pool over 4 GiB"));
        self.index.insert(s.to_string(), i);
        i
    }

    fn emit(&self, out: &mut String, name: &str) {
        writeln!(
            out,
            "pub(crate) static {name}: crate::pool::Pool = crate::pool::Pool {{ text: {:?}, ends: &{:?} }};",
            self.text, self.ends
        )
        .expect("writing to a String does not fail");
    }
}

fn emit_array<T: std::fmt::Debug>(out: &mut String, name: &str, ty: &str, values: &[T]) {
    writeln!(
        out,
        "pub(crate) static {name}: [{ty}; {}] = {:?};",
        values.len(),
        values
    )
    .expect("writing to a String does not fail");
}

fn hex(path: &Path, row: &Row, cell: &str, max: u32) -> u32 {
    match u32::from_str_radix(cell, 16) {
        Ok(v) if v <= max => v,
        _ => bad(path, row, &format!("bad hex value {cell:?}")),
    }
}

fn dec(path: &Path, row: &Row, cell: &str, max: u32) -> u32 {
    match cell.parse::<u32>() {
        Ok(v) if v <= max && !cell.is_empty() && cell.bytes().all(|b| b.is_ascii_digit()) => v,
        _ => bad(path, row, &format!("bad decimal value {cell:?}")),
    }
}

fn text(path: &Path, row: &Row, cell: &str) -> String {
    let t = cell.trim();
    if t.is_empty() {
        bad(path, row, "empty name");
    }
    t.to_string()
}

/// Sorts rows by key and refuses duplicates.
fn sorted<K: Ord + Copy + std::fmt::Debug, V>(
    path: &Path,
    mut v: Vec<(K, V, usize)>,
) -> Vec<(K, V)> {
    v.sort_by_key(|e| e.0);
    for w in v.windows(2) {
        if w[0].0 == w[1].0 {
            panic!(
                "{}: key {:?} on lines {} and {}",
                path.display(),
                w[0].0,
                w[0].2,
                w[1].2
            );
        }
    }
    v.into_iter().map(|(k, val, _)| (k, val)).collect()
}

/// A three-letter lower-case code packed into a `u32` (first letter highest), or a two-letter code.
fn pack_letters(path: &Path, row: &Row, s: &str, len: usize) -> u32 {
    if s.len() != len || !s.bytes().all(|b| b.is_ascii_lowercase()) {
        bad(path, row, &format!("bad language code {s:?}"));
    }
    s.bytes().fold(0u32, |a, b| (a << 8) | b as u32)
}

fn main() {
    let dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("cargo sets CARGO_MANIFEST_DIR"))
        .join("data");
    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("cargo sets OUT_DIR"));
    let mut out = String::from("// Generated by build.rs from the files in data/. Do not edit.\n");

    // Mobile country codes.
    {
        let p = dir.join("mcc.tsv");
        let mut pool = Pool::default();
        let rows = read_rows(&p, 3);
        let v = rows
            .iter()
            .map(|r| {
                let mcc = dec(&p, r, &r.cells[0], 999) as u16;
                let note = match r.cells[2].as_str() {
                    "" => 0u8,
                    n if n.len() == 1 && n.as_bytes()[0].is_ascii_lowercase() => n.as_bytes()[0],
                    _ => bad(&p, r, "bad note"),
                };
                (mcc, (pool.add(&text(&p, r, &r.cells[1])), note), r.line)
            })
            .collect();
        let v = sorted(&p, v);
        emit_array(
            &mut out,
            "MCC_KEYS",
            "u16",
            &v.iter().map(|e| e.0).collect::<Vec<_>>(),
        );
        emit_array(
            &mut out,
            "MCC_AREA",
            "u16",
            &v.iter().map(|e| e.1 .0).collect::<Vec<_>>(),
        );
        emit_array(
            &mut out,
            "MCC_NOTE",
            "u8",
            &v.iter().map(|e| e.1 .1).collect::<Vec<_>>(),
        );
        pool.emit(&mut out, "MCC_POOL");
    }

    // Mobile network codes: key = mcc * 10000 + digits * 1000 + mnc.
    {
        let p = dir.join("mnc.tsv");
        let mut pool = Pool::default();
        let rows = read_rows(&p, 3);
        let v = rows
            .iter()
            .map(|r| {
                let mcc = dec(&p, r, &r.cells[0], 999);
                let digits = r.cells[1].len() as u32;
                if !(2..=3).contains(&digits) {
                    bad(&p, r, "an MNC has two or three digits");
                }
                let mnc = dec(&p, r, &r.cells[1], 999);
                (
                    mcc * 10000 + digits * 1000 + mnc,
                    pool.add(&text(&p, r, &r.cells[2])),
                    r.line,
                )
            })
            .collect();
        let v = sorted(&p, v);
        emit_array(
            &mut out,
            "MNC_KEYS",
            "u32",
            &v.iter().map(|e| e.0).collect::<Vec<_>>(),
        );
        emit_array(
            &mut out,
            "MNC_NAME",
            "u16",
            &v.iter().map(|e| e.1).collect::<Vec<_>>(),
        );
        pool.emit(&mut out, "MNC_POOL");
    }

    // IEEE OUI (MA-L).
    {
        let p = dir.join("oui.tsv");
        let mut pool = Pool::default();
        let rows = read_rows(&p, 2);
        let v = rows
            .iter()
            .map(|r| {
                if r.cells[0].len() != 6 {
                    bad(&p, r, "an OUI has six hex digits");
                }
                (
                    hex(&p, r, &r.cells[0], 0xFF_FFFF),
                    pool.add(&text(&p, r, &r.cells[1])),
                    r.line,
                )
            })
            .collect();
        let v = sorted(&p, v);
        emit_array(
            &mut out,
            "OUI_KEYS",
            "u32",
            &v.iter().map(|e| e.0).collect::<Vec<_>>(),
        );
        emit_array(
            &mut out,
            "OUI_NAME",
            "u16",
            &v.iter().map(|e| e.1).collect::<Vec<_>>(),
        );
        pool.emit(&mut out, "OUI_POOL");
    }

    // ANT+ manufacturer identifiers.
    {
        let p = dir.join("ant_manufacturer.tsv");
        let mut pool = Pool::default();
        let rows = read_rows(&p, 2);
        let v = rows
            .iter()
            .map(|r| {
                (
                    dec(&p, r, &r.cells[0], 0xFFFF) as u16,
                    pool.add(&text(&p, r, &r.cells[1])),
                    r.line,
                )
            })
            .collect();
        let v = sorted(&p, v);
        emit_array(
            &mut out,
            "ANT_MAN_KEYS",
            "u16",
            &v.iter().map(|e| e.0).collect::<Vec<_>>(),
        );
        emit_array(
            &mut out,
            "ANT_MAN_NAME",
            "u16",
            &v.iter().map(|e| e.1).collect::<Vec<_>>(),
        );
        pool.emit(&mut out, "ANT_MAN_POOL");
    }

    // Bluetooth company identifiers.
    {
        let p = dir.join("bt_company.tsv");
        let mut pool = Pool::default();
        let rows = read_rows(&p, 2);
        let v = rows
            .iter()
            .map(|r| {
                (
                    hex(&p, r, &r.cells[0], 0xFFFF) as u16,
                    pool.add(&text(&p, r, &r.cells[1])),
                    r.line,
                )
            })
            .collect();
        let v = sorted(&p, v);
        emit_array(
            &mut out,
            "BT_COMPANY_KEYS",
            "u16",
            &v.iter().map(|e| e.0).collect::<Vec<_>>(),
        );
        emit_array(
            &mut out,
            "BT_COMPANY_NAME",
            "u16",
            &v.iter().map(|e| e.1).collect::<Vec<_>>(),
        );
        pool.emit(&mut out, "BT_COMPANY_POOL");
    }

    // Bluetooth 16-bit UUIDs: kind 0 = service, 1 = member service.
    {
        let p = dir.join("bt_uuid16.tsv");
        let mut pool = Pool::default();
        let rows = read_rows(&p, 3);
        let v = rows
            .iter()
            .map(|r| {
                let kind = match r.cells[1].as_str() {
                    "service" => 0u8,
                    "member" => 1u8,
                    _ => bad(&p, r, "kind is service or member"),
                };
                (
                    hex(&p, r, &r.cells[0], 0xFFFF) as u16,
                    (kind, pool.add(&text(&p, r, &r.cells[2]))),
                    r.line,
                )
            })
            .collect();
        let v = sorted(&p, v);
        emit_array(
            &mut out,
            "BT_UUID_KEYS",
            "u16",
            &v.iter().map(|e| e.0).collect::<Vec<_>>(),
        );
        emit_array(
            &mut out,
            "BT_UUID_KIND",
            "u8",
            &v.iter().map(|e| e.1 .0).collect::<Vec<_>>(),
        );
        emit_array(
            &mut out,
            "BT_UUID_NAME",
            "u16",
            &v.iter().map(|e| e.1 .1).collect::<Vec<_>>(),
        );
        pool.emit(&mut out, "BT_UUID_POOL");
    }

    // LoRaWAN NetID allocations.
    {
        let p = dir.join("lorawan_netid.tsv");
        let mut pool = Pool::default();
        let rows = read_rows(&p, 3);
        let v = rows
            .iter()
            .map(|r| {
                let first = hex(&p, r, &r.cells[0], 0xFF_FFFF);
                let count = dec(&p, r, &r.cells[1], 0xFFFF);
                if count == 0 {
                    bad(&p, r, "count is at least 1");
                }
                (first, (count, pool.add(&text(&p, r, &r.cells[2]))), r.line)
            })
            .collect();
        let v = sorted(&p, v);
        for w in v.windows(2) {
            if w[0].0 + w[0].1 .0 > w[1].0 {
                panic!(
                    "{}: NetID run at {:06X} overlaps {:06X}",
                    p.display(),
                    w[0].0,
                    w[1].0
                );
            }
        }
        emit_array(
            &mut out,
            "NETID_FIRST",
            "u32",
            &v.iter().map(|e| e.0).collect::<Vec<_>>(),
        );
        emit_array(
            &mut out,
            "NETID_COUNT",
            "u16",
            &v.iter().map(|e| e.1 .0 as u16).collect::<Vec<_>>(),
        );
        emit_array(
            &mut out,
            "NETID_NAME",
            "u16",
            &v.iter().map(|e| e.1 .1).collect::<Vec<_>>(),
        );
        pool.emit(&mut out, "NETID_POOL");
    }

    // ISO 639-2 languages: rows sorted by the bibliographic code, with indexes by terminology code and by ISO 639-1 code.
    {
        let p = dir.join("iso639_2.tsv");
        let mut pool = Pool::default();
        let rows = read_rows(&p, 4);
        let v = rows
            .iter()
            .map(|r| {
                let b = pack_letters(&p, r, &r.cells[0], 3);
                let t = if r.cells[1].is_empty() {
                    0
                } else {
                    pack_letters(&p, r, &r.cells[1], 3)
                };
                let a2 = if r.cells[2].is_empty() {
                    0
                } else {
                    pack_letters(&p, r, &r.cells[2], 2)
                };
                (b, (t, a2, pool.add(&text(&p, r, &r.cells[3]))), r.line)
            })
            .collect();
        let v = sorted(&p, v);
        emit_array(
            &mut out,
            "LANG_B",
            "u32",
            &v.iter().map(|e| e.0).collect::<Vec<_>>(),
        );
        emit_array(
            &mut out,
            "LANG_T",
            "u32",
            &v.iter().map(|e| e.1 .0).collect::<Vec<_>>(),
        );
        emit_array(
            &mut out,
            "LANG_A2",
            "u32",
            &v.iter().map(|e| e.1 .1).collect::<Vec<_>>(),
        );
        emit_array(
            &mut out,
            "LANG_NAME",
            "u16",
            &v.iter().map(|e| e.1 .2).collect::<Vec<_>>(),
        );
        let by_t = sorted(
            &p,
            v.iter()
                .enumerate()
                .filter(|(_, e)| e.1 .0 != 0)
                .map(|(i, e)| (e.1 .0, i as u16, 0))
                .collect(),
        );
        emit_array(&mut out, "LANG_BY_T", "(u32, u16)", &by_t);
        let by_a2 = sorted(
            &p,
            v.iter()
                .enumerate()
                .filter(|(_, e)| e.1 .1 != 0)
                .map(|(i, e)| (e.1 .1, i as u16, 0))
                .collect(),
        );
        emit_array(&mut out, "LANG_BY_A2", "(u32, u16)", &by_a2);
        pool.emit(&mut out, "LANG_POOL");
    }

    fs::write(out_dir.join("tables.rs"), out).expect("OUT_DIR is writable");
    println!("cargo:rerun-if-changed=build.rs");
}
