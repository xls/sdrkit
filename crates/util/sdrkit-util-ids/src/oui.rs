//! IEEE organizationally unique identifiers (OUI, the MA-L assignments): the maker named by the first three bytes of a MAC
//! address, a Wi-Fi BSSID, a Bluetooth public device address or an EUI-64 such as a LoRaWAN DevEUI.
//!
//! **Data.** `data/oui.tsv` is a **subset** of the IEEE Registration Authority's public MA-L listing
//! (<https://standards-oui.ieee.org/oui/oui.csv>, file of 8 November 2026, 40,458 assignments): every assignment of each
//! organisation that holds 20 or more, plus every assignment of the organisations matched by `data/oui_keep.txt` (radio,
//! network and IoT makers often heard on the air). The subset holds 17,216 of the 40,351 named assignments, of 242
//! organisations, and costs about 110 KB in the binary; the full listing would cost about 750 KB. Organisation names are as IEEE publishes them.
//! MA-M and MA-S assignments (28-bit and 36-bit prefixes inside IEEE's own MA-L) are not included: their MA-L lookup returns
//! "IEEE Registration Authority".
//!
//! **Update** (or take the whole listing):
//!
//! ```text
//! curl -O https://standards-oui.ieee.org/oui/oui.csv
//! cargo run -p sdrkit-util-ids --example update_tables -- oui oui.csv crates/util/sdrkit-util-ids/data/oui_keep.txt 20 \
//!     > crates/util/sdrkit-util-ids/data/oui.tsv
//! # the whole listing: give 1 as the threshold
//! ```
//!
//! ```
//! use sdrkit_util_ids::oui;
//!
//! assert_eq!(oui::vendor([0xAC, 0xBC, 0x32]), Some("Apple, Inc."));
//! assert_eq!(oui::vendor_of_address(&[0x24, 0x0A, 0xC4, 0x01, 0x02, 0x03]), Some("Espressif Inc."));
//! assert_eq!(oui::vendor_of_address(&[0x02, 0x0A, 0xC4, 0x01, 0x02, 0x03]), None); // locally administered
//! ```

use crate::pool::{self, find};

/// The maker of an OUI.
pub fn vendor(oui: [u8; 3]) -> Option<&'static str> {
    let key = (oui[0] as u32) << 16 | (oui[1] as u32) << 8 | oui[2] as u32;
    find(&pool::OUI_KEYS, &key).map(|i| pool::OUI_POOL.get(pool::OUI_NAME[i]))
}

/// Whether the first byte of an address marks it as locally administered (bit 1, IEEE 802 clause 8.2): such an address was
/// generated by the device (random MAC addresses of phones, virtual interfaces) and identifies no maker.
pub const fn is_locally_administered(first_byte: u8) -> bool {
    first_byte & 0x02 != 0
}

/// Whether the first byte of an address marks a group (multicast) address (bit 0).
pub const fn is_group(first_byte: u8) -> bool {
    first_byte & 0x01 != 0
}

/// The maker of a MAC address or EUI-64 (at least three bytes, first byte first): `None` for a locally administered or group
/// address, a short slice, or an OUI not in the table.
pub fn vendor_of_address(addr: &[u8]) -> Option<&'static str> {
    match addr {
        [a, b, c, ..] if !is_locally_administered(*a) && !is_group(*a) => vendor([*a, *b, *c]),
        _ => None,
    }
}

/// The number of OUIs in the table.
pub fn len() -> usize {
    pool::OUI_KEYS.len()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn known_assignments_from_the_ieee_listing() {
        assert_eq!(vendor([0x00, 0x00, 0x0C]), Some("Cisco Systems, Inc"));
        assert_eq!(vendor([0xAC, 0xBC, 0x32]), Some("Apple, Inc."));
        assert_eq!(vendor([0x24, 0x0A, 0xC4]), Some("Espressif Inc."));
        assert_eq!(vendor([0xB8, 0x27, 0xEB]), Some("Raspberry Pi Foundation"));
        assert_eq!(vendor([0xDC, 0xA6, 0x32]), Some("Raspberry Pi Trading Ltd"));
        assert_eq!(vendor([0x00, 0x04, 0x0E]), Some("AVM GmbH"));
        assert_eq!(vendor([0x4C, 0x5E, 0x0C]), Some("Routerboard.com"));
        assert_eq!(
            vendor([0x70, 0xB3, 0xD5]),
            Some("IEEE Registration Authority")
        );
        assert_eq!(vendor([0xFF, 0xFF, 0xFF]), None);
        assert!(len() > 15_000);
    }

    #[test]
    fn ieee_802_15_4_makers_are_kept() {
        // Zigbee and Thread radios: their IEEE names, as the MA-L listing prints them.
        for (oui, name) in [
            ([0x00, 0x0D, 0x6F], "Ember Corporation"),
            ([0xD0, 0xCF, 0x5E], "Energy Micro AS"),
            ([0x00, 0x17, 0x88], "Philips Lighting BV"),
            ([0x00, 0x15, 0x8D], "Jennic Ltd"),
            ([0x04, 0xCF, 0x8C], "XIAOMI Electronics,CO.,LTD"),
            ([0x54, 0xEF, 0x44], "Lumi United Technology Co., Ltd"),
            ([0x28, 0x6D, 0x97], "SAMJIN Co., Ltd."),
            ([0x24, 0xFD, 0x5B], "SmartThings, Inc."),
            ([0x00, 0x13, 0xA2], "MaxStream, Inc"),
            ([0x00, 0x07, 0x81], "Itron Inc."),
            ([0x00, 0x21, 0x2E], "dresden-elektronik"),
            ([0x00, 0x21, 0xED], "Telegesis"),
        ] {
            assert_eq!(vendor(oui), Some(name), "{oui:02X?}");
        }
    }

    #[test]
    fn address_bits() {
        assert!(is_locally_administered(0x02) && !is_locally_administered(0x00));
        assert!(is_group(0x01) && !is_group(0x00));
        assert_eq!(vendor_of_address(&[0x01, 0x00, 0x0C, 0, 0, 0]), None);
        assert_eq!(vendor_of_address(&[0x00, 0x00]), None);
        assert_eq!(
            vendor_of_address(&[0x00, 0x00, 0x0C]),
            Some("Cisco Systems, Inc")
        );
    }
}
